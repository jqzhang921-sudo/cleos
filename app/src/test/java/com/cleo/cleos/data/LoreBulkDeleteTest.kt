package com.cleo.cleos.data

import com.cleo.cleos.data.db.LoreDao
import com.cleo.cleos.data.db.LoreEntity
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flowOf
import kotlinx.coroutines.runBlocking
import org.junit.Assert.*
import org.junit.Test

class LoreBulkDeleteTest {
    @Test fun largeImportsAreDeletedInBoundedBatchesAndOnlyForTheirOwner() = runBlocking {
        val dao = FakeLore()
        (1L..13_382L).forEach { dao.rows[it] = entry(it, 7L) }
        dao.rows[20_000L] = entry(20_000L, 8L)
        dao.rows[20_001L] = entry(20_001L, 7L)
        val ids = (1L..13_382L).toList() + listOf(1L, 20_000L, 99_999L)
        assertEquals(13_382, dao.deleteSelected(7L, ids))
        assertEquals(27, dao.batches.size)
        assertTrue(dao.batches.all { it.size <= 500 })
        assertEquals(ids.distinct().size, dao.batches.sumOf { it.size })
        assertEquals(setOf(20_000L, 20_001L), dao.rows.keys)
    }

    @Test fun anEmptySelectionDoesNotExecuteAnInQuery() = runBlocking {
        val dao = FakeLore()
        assertEquals(0, dao.deleteSelected(7L, emptyList()))
        assertTrue(dao.batches.isEmpty())
    }

    private fun entry(id: Long, owner: Long) = LoreEntity(id = id, companionId = owner,
        title = "synthetic $id", content = "fixture", createdAt = 1L, updatedAt = 1L)

    /** Exercises the DAO's default batching routine; SQL/transactions are generated by Room. */
    private class FakeLore : LoreDao {
        val rows = linkedMapOf<Long, LoreEntity>()
        val batches = mutableListOf<List<Long>>()
        override suspend fun deleteBatch(companionId: Long, ids: List<Long>): Int {
            assertTrue(ids.isNotEmpty())
            batches += ids.toList()
            var count = 0
            for (id in ids) if (rows[id]?.companionId == companionId) { rows.remove(id); count++ }
            return count
        }
        override fun observeFor(companionId: Long): Flow<List<LoreEntity>> = flowOf(rows.values.filter { it.companionId == companionId })
        override suspend fun allFor(companionId: Long) = rows.values.filter { it.companionId == companionId }
        override suspend fun get(id: Long) = rows[id]
        override suspend fun insert(entry: LoreEntity): Long { rows[entry.id] = entry; return entry.id }
        override suspend fun update(entry: LoreEntity) { rows[entry.id] = entry }
        override suspend fun delete(id: Long) { rows.remove(id) }
        override suspend fun deleteFor(companionId: Long) { rows.entries.removeAll { it.value.companionId == companionId } }
        override suspend fun all() = rows.values.toList()
        override suspend fun insertAll(items: List<LoreEntity>) { items.forEach { rows[it.id] = it } }
        override suspend fun clear() { rows.clear() }
    }
}
